def count_berries(game) -> int:
    """Подсчёт суммарного количества любых ягод в инвентаре."""
    inv = getattr(game, "inventory", {}) or {}
    return sum(inv.get(b, 0) for b in BERRY_NAMES)


def consume_berries(game, amount: int = 5) -> int:
    """Списание ягод из инвентаря. Возвращает списанное количество."""
    needed = amount
    inv = getattr(game, "inventory", {}) or {}
    for b in BERRY_NAMES:
        have = inv.get(b, 0)
        if have > 0:
            take = min(have, needed)
            inv[b] -= take
            if inv[b] <= 0:
                inv.pop(b, None)
            needed -= take
            if needed <= 0:
                break
    return amount - needed


