def get_item_description(item_name: str) -> str:
    return ITEMS.get(item_name, {}).get("description", "Нет описания")


def get_item_type(item_name: str) -> str:
    return ITEMS.get(item_name, {}).get("type", "misc")


def get_item_rank(item_name: str) -> int:
    return int(ITEMS.get(item_name, {}).get("rank", 1))


def get_item_rank_marker(item_name: str) -> str:
    rank = get_item_rank(item_name)
    return RANKS.get(rank, {}).get("marker", "⚪")


def get_item_rank_name(item_name: str) -> str:
    rank = get_item_rank(item_name)
    return RANKS.get(rank, {}).get("name", "Обычный")


def get_item_display_name(item_name: str) -> str:
    """Возвращает название предмета с маркером ранга качества."""
    marker = get_item_rank_marker(item_name)
    return f"{marker} {item_name}"


def get_item_effects(item_name: str) -> Dict[str, int]:
    return dict(ITEMS.get(item_name, {}).get("effects", {}))


def get_item_negative_effects(item_name: str) -> Optional[Dict[str, Any]]:
    return ITEMS.get(item_name, {}).get("negative_effects")


def get_item_stackable(item_name: str) -> bool:
    return ITEMS.get(item_name, {}).get("stackable", True)


def get_all_items() -> Dict[str, Dict]:
    return ITEMS.copy()


def is_berry(item_name: str) -> bool:
    return item_name in BERRY_ITEMS or get_item_type(item_name) == "berry"


def is_mushroom(item_name: str) -> bool:
    return item_name in MUSHROOM_ITEMS or get_item_type(item_name) == "mushroom"


def _item_can_use(item_name: str) -> bool:
    return ITEMS.get(item_name, {}).get("can_use", True)


def _has_consumable_effects(item_name: str) -> bool:
    effects = ITEMS.get(item_name, {}).get("effects", {})
    return any(k in CONSUMABLE_EFFECT_KEYS for k in effects)


def _is_consumable_type(item_name: str) -> bool:
    return get_item_type(item_name) in {"food", "drink", "berry", "mushroom", "potion"}


def is_item_consumable(item_name: str) -> bool:
    """
    Определяет, должен ли предмет попадать в меню «Использовать» (расходники).
    """
    if not _item_can_use(item_name):
        return False
    if _has_consumable_effects(item_name):
        return True
    if _is_consumable_type(item_name):
        return True
    return False


def format_item_card(item_name: str) -> str:
    """
    Форматирует информационную карточку предмета:
    1. Название и маркер ранга
    2. Художественное описание
    3. Положительные эффекты
    4. Негативные эффекты / риски с шансом
    5. Примечания
    """
    data = ITEMS.get(item_name, {})
    if not data:
        return f"📦 **{item_name}**\n\n_Информация отсутствует._"

    marker = get_item_rank_marker(item_name)
    rank_name = get_item_rank_name(item_name)
    title = f"{marker} {item_name} ({rank_name})"

    lines = [f"📦 **{title}**", ""]

    # 1. Художественное описание
    desc = data.get("description", "")
    if desc:
        lines.append(f"_{desc}_")
        lines.append("")

    # 2. Положительные эффекты
    effects = data.get("effects", {})
    eff_parts = []
    if effects.get("hunger"):
        eff_parts.append(f"🍖 Сытость: +{effects['hunger']}")
    if effects.get("thirst"):
        eff_parts.append(f"💧 Жажда: +{effects['thirst']}")
    if effects.get("hp"):
        hp_val = effects["hp"]
        eff_parts.append(f"❤️ Здоровье: {'+' if hp_val > 0 else ''}{hp_val} HP")
    if effects.get("light"):
        eff_parts.append(f"💡 Освещение: +{effects['light']}")

    lines.append("✨ **Эффекты:** " + (", ".join(eff_parts) if eff_parts else "Нет прямых эффектов"))

    # 3. Негативные эффекты / риски
    neg = data.get("negative_effects")
    if neg:
        lines.append(f"⚠️ **Негативный эффект:** {neg.get('description', 'Неизвестно')}")
    else:
        lines.append("⚠️ **Негативный эффект:** Отсутствуют")

    # 4. Примечание
    note = data.get("note")
    if note:
        lines.append(f"📌 **Примечание:** {note}")

    return "\n".join(lines)
